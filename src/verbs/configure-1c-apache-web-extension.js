import path from 'node:path';
import { config } from '../configure.js';
import { withGuestSession } from '../infrastructure/with-guest-session.js';
import { executeGuestPowerShell, quotePowerShell } from '../infrastructure/execute-guest-powershell.js';
import { isApacheHttpdInstalled, readApacheHttpdState } from '../infrastructure/read-apache-httpd-state.js';
import { assertOneCPlatformInstalled } from '../infrastructure/read-1c-platform-state.js';
import { waitForHttp } from '../lib/wait-for-http.js';

function buildConfigureScript(oneC, apacheHttpd) {
    const httpdPath = path.win32.join(apacheHttpd.installationDirectory, 'bin', 'httpd.exe');
    const mainConfigurationPath = path.win32.join(apacheHttpd.installationDirectory, 'conf', 'httpd.conf');
    const extensionDirectory = path.win32.join(apacheHttpd.installationDirectory, 'conf', 'extra');
    const extensionConfigurationPath = path.win32.join(extensionDirectory, apacheHttpd.guest.configurationFilename);
    const wsapPath = path.win32.join(oneC.installationDirectory, 'bin', 'wsap24.dll').replaceAll('\\', '/');
    const includeLine = `Include conf/extra/${apacheHttpd.guest.configurationFilename}`;
    return [
        '$ErrorActionPreference = "Stop"',
        `$httpdPath = ${quotePowerShell(httpdPath)}`,
        `$mainConfigurationPath = ${quotePowerShell(mainConfigurationPath)}`,
        `$extensionDirectory = ${quotePowerShell(extensionDirectory)}`,
        `$extensionConfigurationPath = ${quotePowerShell(extensionConfigurationPath)}`,
        `$includeMarker = ${quotePowerShell(apacheHttpd.guest.managedBlockMarker)}`,
        `$includeLine = ${quotePowerShell(includeLine)}`,
        `$modulePath = ${quotePowerShell(wsapPath)}`,
        'if (-not (Test-Path -LiteralPath $modulePath -PathType Leaf)) { throw "1C Apache module is missing: $modulePath" }',
        'New-Item -ItemType Directory -Path $extensionDirectory -Force | Out-Null',
        '$moduleConfiguration = "# Managed by autosetup. Do not edit this file." + [Environment]::NewLine + "LoadModule _1cws_module `"$modulePath`"" + [Environment]::NewLine',
        '[IO.File]::WriteAllText($extensionConfigurationPath, $moduleConfiguration, [Text.UTF8Encoding]::new($false))',
        // Управляемый блок с маркерами, а не слепой append: повторный
        // запуск переписывает СВОИ строки, а не копит их, и блок можно
        // однозначно найти/убрать, не гадая, что тут наше.
        '$newLine = [Environment]::NewLine',
        '$managedBlock = "# BEGIN $includeMarker" + $newLine + $includeLine + $newLine + "# END $includeMarker" + $newLine',
        '$mainConfiguration = [IO.File]::ReadAllText($mainConfigurationPath)',
        '$blockPattern = "(?ms)^# BEGIN " + [regex]::Escape($includeMarker) + ".*?^# END " + [regex]::Escape($includeMarker) + "\\r?\\n?"',
        'if ($mainConfiguration -match $blockPattern) {',
        '  $mainConfiguration = [regex]::Replace($mainConfiguration, $blockPattern, [System.Text.RegularExpressions.MatchEvaluator]{ param($m) $managedBlock })',
        '} else {',
        '  $mainConfiguration = $mainConfiguration + $newLine + $managedBlock',
        '}',
        '[IO.File]::WriteAllText($mainConfigurationPath, $mainConfiguration, [Text.UTF8Encoding]::new($false))',
        '& $httpdPath -t',
        'if ($LASTEXITCODE -ne 0) { throw "Apache configuration validation with 1C module failed" }',
        `Restart-Service -Name ${quotePowerShell(apacheHttpd.serviceName)} -ErrorAction Stop`,
    ].join('\n');
}

export async function configureOneCApacheWebExtension() {
    const { oneC, apacheHttpd } = config;
    await withGuestSession(async ({ ssh }) => {
        await assertOneCPlatformInstalled(ssh, oneC);
        const apacheState = await readApacheHttpdState(ssh, apacheHttpd);
        if (!isApacheHttpdInstalled(apacheState, apacheHttpd)) {
            throw new Error(`Apache HTTP Server must be installed before 1C integration: ${JSON.stringify(apacheState)}`);
        }
        await executeGuestPowerShell(ssh, buildConfigureScript(oneC, apacheHttpd), 'configure Apache 1C web extension');
    });
    await waitForHttp({
        url: `http://${apacheHttpd.hostAddress}:${apacheHttpd.hostPort}/`,
        timeoutMs: apacheHttpd.guest.httpReadyTimeoutMs,
        pollIntervalMs: apacheHttpd.guest.httpReadyPollIntervalMs,
    });
    console.log('Apache 1C web extension: configured');
}

if (import.meta.url === `file://${process.argv[1]}`) {
    configureOneCApacheWebExtension().catch((error) => {
        console.error(error.message);
        process.exit(1);
    });
}
